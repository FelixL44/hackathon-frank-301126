// Writes src/storage/fixture-files.ts: the synthetic evidence in fixtures/files as base64.
// Cloudflare Workers have no project file system, so the app reads fixture evidence from this module.
// Run after changing fixtures/files: npm run fixtures:embed (objects.test.ts fails while it is stale).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const root = join(import.meta.dirname, "files");
const files = readdirSync(root, { recursive: true, withFileTypes: true })
  .filter((d) => d.isFile() && !d.name.endsWith(".md"))
  .map((d) => join(d.parentPath, d.name))
  .sort();
const entries = files.map((f) => `  ${JSON.stringify(relative(root, f).split(sep).join("/"))}: ${JSON.stringify(readFileSync(f).toString("base64"))},`);
writeFileSync(
  join(import.meta.dirname, "..", "src", "storage", "fixture-files.ts"),
  `// Generated by fixtures/embed.ts. Do not edit.\nexport const FIXTURE_FILES: Record<string, string> = {\n${entries.join("\n")}\n};\n`,
);
console.log(`embedded ${files.length} fixture files`);
